// Fast lookup index by Surah
const SURAH_OCCASIONS_INDEX: Record<number, AyahRevelationOccasion[]> = {};
for (const occ of AYAH_ASBAB_AL_NUZUL) {
  if (!SURAH_OCCASIONS_INDEX[occ.surahNumber]) {
    SURAH_OCCASIONS_INDEX[occ.surahNumber] = [];
  }
  SURAH_OCCASIONS_INDEX[occ.surahNumber].push(occ);
}

export function getSurahRevelationHistory(surahNumber: number): SurahRevelationHistory {
  return (
    SURAH_REVELATION_HISTORY[surahNumber] || {
      surahNumber,
      revelationOrder: surahNumber,
      phase: 'Late Makkan',
      approximateEra: 'Prophetic Era (610–632 CE)',
      prophetSituation: 'Revealed during the Messenger’s (ﷺ) mission calling humanity to pure monotheism and mercy.',
      historicalSummary: 'Revealed to guide believers through faith, gratitude, and steadfast moral purpose.',
      keyThemes: 'Tawhid, Accountability & Prophetic Guidance.',
      sourceReference: 'Tafsir Ibn Kathir',
    }
  );
}

export function getSurahOccasions(surahNumber: number): AyahRevelationOccasion[] {
  return SURAH_OCCASIONS_INDEX[surahNumber] || [];
}

export interface VerseRevelationContext {
  surahHistory: SurahRevelationHistory;
  verseOccasion: AyahRevelationOccasion | null;
  surahOccasions: AyahRevelationOccasion[];
}

export function getVerseRevelationContext(
  surahNumber: number,
  ayahNumber: number
): VerseRevelationContext {
  const surahHistory = getSurahRevelationHistory(surahNumber);
  const surahOccasions = getSurahOccasions(surahNumber);
  const verseOccasion =
    surahOccasions.find(
      (occ) => ayahNumber >= occ.fromAyah && ayahNumber <= occ.toAyah
    ) || null;

  return {
    surahHistory,
    verseOccasion,
    surahOccasions,
  };
}
