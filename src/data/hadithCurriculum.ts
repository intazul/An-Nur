export const HADITH_CURRICULUM: HadithLessonItem[] = RAW_LESSONS.map((lesson, idx) => {
  const topic = HADITH_TOPICS.find((t) => t.id === lesson.topicId)!;
  return {
    ...lesson,
    globalNumber: idx + 1,
    chapterNumber: topic.chapterNumber,
    topicTitle: topic.titleEnglish,
  };
});

export function getLessonsForTopic(topicId: HadithTopicId): HadithLessonItem[] {
  return HADITH_CURRICULUM.filter((l) => l.topicId === topicId);
}

export function getTopicDistributionStats(learnedIds: string[]): {
  topic: HadithTopicMeta;
  totalCount: number;
  learnedCount: number;
  progressPercent: number;
  sharePercent: number;
}[] {
  const learnedSet = new Set(learnedIds);
  const totalCurriculum = HADITH_CURRICULUM.length;

  return HADITH_TOPICS.map((topic) => {
    const lessons = getLessonsForTopic(topic.id);
    const totalCount = lessons.length;
    const learnedCount = lessons.filter((l) => learnedSet.has(l.id)).length;
    const progressPercent = totalCount > 0 ? Math.round((learnedCount / totalCount) * 100) : 0;
    const sharePercent = totalCurriculum > 0 ? Math.round((totalCount / totalCurriculum) * 100) : 0;
    return {
      topic,
      totalCount,
      learnedCount,
      progressPercent,
      sharePercent,
    };
  });
}

export function searchCurriculumLessons(query: string): HadithLessonItem[] {
  const q = query.trim().toLowerCase();
  if (q.length < 2) return [];
  return HADITH_CURRICULUM.filter(
    (l) =>
      l.lessonTitle.toLowerCase().includes(q) ||
      l.topicTitle.toLowerCase().includes(q) ||
      l.question.toLowerCase().includes(q) ||
      l.textEnglish.toLowerCase().includes(q) ||
      l.corePhraseEnglish.toLowerCase().includes(q) ||
      l.narrator.toLowerCase().includes(q) ||
      l.reference.toLowerCase().includes(q) ||
      l.keyLesson.toLowerCase().includes(q) ||
      l.textArabic.includes(query.trim())
  );
}
